#!/bin/bash
# thinfloe-time apply installs the zone and the NTP servers of
# generated/time, and refuses a file it cannot trust without changing
# anything. timedatectl, systemctl and chronyc are stubs that log their
# arguments; /etc, the zoneinfo tree and the home are scratch directories.
#
# Usage: test/integration/test-thinfloe-time.sh

set -uo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
TOOL="$REPO/overlay/usr/bin/thinfloe-time"
SCRATCH="$(mktemp -d)" || exit 1
trap 'rm -rf "$SCRATCH"' EXIT

fail=0
ok()  { echo "ok   - $1"; }
bad() { echo "FAIL - $1"; fail=1; }
check() { local label=$1; shift; if "$@"; then ok "$label"; else bad "$label"; fi; }

STUBS="$SCRATCH/stubs"
mkdir -p "$STUBS"
for t in timedatectl systemctl chronyc; do
    cat >"$STUBS/$t" <<STUB
#!/bin/bash
echo "$t \$*" >>"$SCRATCH/calls"
exit \${STUB_${t^^}_RC:-0}
STUB
    chmod +x "$STUBS/$t"
done

ZI="$SCRATCH/zoneinfo"
mkdir -p "$ZI/Europe" "$ZI/Asia"
printf 'TZif2' >"$ZI/Europe/Zurich"; printf 'TZif2' >"$ZI/UTC"; printf 'TZif2' >"$ZI/Asia/Tokyo"
printf '# comment\nCH\t+4723+00832\tEurope/Zurich\nJP\t+353916+1394441\tAsia/Tokyo\nXX\t+0\tEurope/Gone\n' >"$ZI/zone.tab"

# fresh: a new /etc with the Ubuntu pools file, an empty home, no calls.
fresh() {
    ETC="$SCRATCH/etc"; HOMED="$SCRATCH/home"
    rm -rf "$ETC" "$HOMED" "$SCRATCH/calls" "$SCRATCH/lock" "$SCRATCH/pending" "$SCRATCH/chrony-dhcp"
    mkdir -p "$ETC/chrony/sources.d" "$HOMED/.config/thinfloe/generated"
    echo "pool 1.ntp.ubuntu.com iburst" >"$ETC/chrony/sources.d/ubuntu-ntp-pools.sources"
    : >"$SCRATCH/calls"
}
gen() { printf '%b' "$1" >"$HOMED/.config/thinfloe/generated/time"; }
apply() {
    TF_TIME_HOME="$HOMED" TF_TIME_ETC="$ETC" TF_TIME_ZONEINFO="$ZI" \
    TF_TIME_TIMEDATECTL="$STUBS/timedatectl" TF_TIME_SYSTEMCTL="$STUBS/systemctl" \
    TF_TIME_CHRONYC="$STUBS/chronyc" TF_TIME_LOCK="$SCRATCH/lock" \
    TF_TIME_PENDING="$SCRATCH/pending" TF_TIME_CHRONY_DHCP="$SCRATCH/chrony-dhcp" \
        python3 -I "$TOOL" "$@" >"$SCRATCH/out" 2>"$SCRATCH/err"
}
called() { grep -qxF -- "$1" "$SCRATCH/calls"; }
not_called() { ! grep -q -- "$1" "$SCRATCH/calls"; }
snapshot() { (cd "$ETC" && find . -type f -printf '%p ' -exec cat {} \; | sort); }

H="# Generated by the ThinFloe menu from ~/.config/thinfloe/config.toml. Edits here are lost.\n"
SRC="$SCRATCH/etc/chrony/sources.d"

# --- a zone
fresh; gen "${H}zone=Europe/Zurich\n"
apply apply; rc=$?
check "zone: exit 0" test $rc -eq 0
check "zone: ok JSON" grep -qxF '{"result": "ok", "reason": ""}' "$SCRATCH/out"
check "zone: timedatectl set-timezone" called "timedatectl set-timezone -- Europe/Zurich"
check "zone: /etc/thinfloe/time" diff <(printf 'zone=Europe/Zurich\n') "$ETC/thinfloe/time"
check "zone: watcher restarted" called "systemctl restart thinfloe-dhcp-timezone.service"
check "zone: no chrony reload (servers unchanged)" not_called chronyc
check "zone: pools untouched" test -f "$SRC/ubuntu-ntp-pools.sources"
check "zone: mode 644" test "$(stat -c %a "$ETC/thinfloe/time")" = 644

# --- back to automatic after a zone: UTC, watcher sets the DHCP zone
: >"$SCRATCH/calls"; rm "$HOMED/.config/thinfloe/generated/time"
apply apply; rc=$?
check "automatic: exit 0" test $rc -eq 0
check "automatic: UTC set" called "timedatectl set-timezone UTC"
check "automatic: watcher restarted" called "systemctl restart thinfloe-dhcp-timezone.service"
check "automatic: /etc/thinfloe/time gone" test ! -e "$ETC/thinfloe/time"

# --- automatic with no zone before: the zone is not touched
: >"$SCRATCH/calls"
apply apply
check "automatic twice: no timedatectl" not_called timedatectl

# --- servers replace the pools
fresh; gen "${H}ntp=ntp.example.ch\nntp=10.1.2.3\n"
apply apply; rc=$?
check "servers: exit 0" test $rc -eq 0
check "servers: sources file" diff <(printf 'server ntp.example.ch iburst\nserver 10.1.2.3 iburst\n') "$SRC/thinfloe.sources"
check "servers: pools off" test -f "$SRC/ubuntu-ntp-pools.sources.thinfloe-off" -a ! -e "$SRC/ubuntu-ntp-pools.sources"
check "servers: /etc/thinfloe/time" diff <(printf 'ntp=ntp.example.ch\nntp=10.1.2.3\n') "$ETC/thinfloe/time"
check "servers: no zone change" not_called timedatectl
check "servers: chrony reloaded" called "chronyc reload sources"

# --- the same servers again: nothing about servers changed, no reload
: >"$SCRATCH/calls"
apply apply; rc=$?
check "same servers: exit 0" test $rc -eq 0
check "same servers: no chrony reload" not_called chronyc

# --- a zone added to the same servers: no reload, so a failing chronyc does not matter
: >"$SCRATCH/calls"; gen "${H}zone=Asia/Tokyo\nntp=ntp.example.ch\nntp=10.1.2.3\n"
STUB_CHRONYC_RC=1 apply apply; rc=$?
check "zone_only_change_skips_reload: exit 0" test $rc -eq 0
check "zone_only_change_skips_reload: zone set" called "timedatectl set-timezone -- Asia/Tokyo"
check "zone_only_change_skips_reload: no chrony reload" not_called chronyc

# --- back to automatic restores the pools
rm "$HOMED/.config/thinfloe/generated/time"
apply apply
check "back_to_automatic_restores_the_pools" test -f "$SRC/ubuntu-ntp-pools.sources" -a ! -e "$SRC/ubuntu-ntp-pools.sources.thinfloe-off" -a ! -e "$SRC/thinfloe.sources"

# --- a reload that fails is a failure with the menu's reason
fresh; gen "${H}ntp=10.0.0.1\n"
STUB_CHRONYC_RC=1 apply apply; rc=$?
check "reload fails: exit 1" test $rc -eq 1
check "reload fails: reason" grep -qF 'The time service did not take the servers.' "$SCRATCH/out"
# the retry with the same servers reloads again: the failed reload is remembered
: >"$SCRATCH/calls"
apply apply; rc=$?
check "retry_after_failed_reload: exit 0" test $rc -eq 0
check "retry_after_failed_reload: chrony reloaded" called "chronyc reload sources"
: >"$SCRATCH/calls"
apply apply
check "retry_after_failed_reload: then no reload" not_called chronyc

# --- automatic, zone only: a failing chronyc is not called and not fatal
fresh; gen "${H}zone=Europe/Zurich\n"
STUB_CHRONYC_RC=1 apply apply; rc=$?
check "zone only, chronyc broken: exit 0" test $rc -eq 0

# --- menu servers remove the DHCP servers file, even when the watcher restart fails
fresh; mkdir -p "$SCRATCH/chrony-dhcp"; echo "server 10.9.9.9 iburst" >"$SCRATCH/chrony-dhcp/thinfloe.sources"
gen "${H}ntp=10.0.0.1\n"
STUB_SYSTEMCTL_RC=1 apply apply; rc=$?
check "menu_servers_remove_dhcp_file: exit 0" test $rc -eq 0
check "menu_servers_remove_dhcp_file: file gone" test ! -e "$SCRATCH/chrony-dhcp/thinfloe.sources"
check "menu_servers_remove_dhcp_file: chrony reloaded" called "chronyc reload sources"

# --- automatic leaves the DHCP servers file to the watcher
fresh; mkdir -p "$SCRATCH/chrony-dhcp"; echo "server 10.9.9.9 iburst" >"$SCRATCH/chrony-dhcp/thinfloe.sources"
apply apply
check "automatic: DHCP servers file kept" test -f "$SCRATCH/chrony-dhcp/thinfloe.sources"
check "automatic: no chrony reload" not_called chronyc

# --- hostile files: exit 1, nothing changed, nothing called
hostile() { # label, setup command
    local label=$1; shift
    fresh; "$@"
    local before; before=$(snapshot)
    apply apply; local rc=$?
    check "$label: exit 1" test $rc -eq 1
    check "$label: failed JSON" grep -q '"result": "failed"' "$SCRATCH/out"
    check "$label: nothing changed" test "$(snapshot)" = "$before"
    check "$label: nothing called" test ! -s "$SCRATCH/calls"
}
G="$SCRATCH/home/.config/thinfloe/generated"
link_file() { echo "zone=Europe/Zurich" >"$SCRATCH/outside"; ln -s "$SCRATCH/outside" "$G/time"; }
link_dir() { mkdir -p "$SCRATCH/elsewhere"; echo "zone=Europe/Zurich" >"$SCRATCH/elsewhere/time"; rm -rf "$G"; ln -s "$SCRATCH/elsewhere" "$G"; }
fifo() { mkfifo "$G/time"; }
big() { { printf 'zone=Europe/Zurich\n'; head -c 70000 /dev/zero | tr '\0' '#'; } >"$G/time"; }
nine() { for i in 1 2 3 4 5 6 7 8 9; do echo "ntp=10.0.0.$i"; done >"$G/time"; }
hostile "symlinked file" link_file
hostile "symlinked generated dir" link_dir
hostile "fifo" fifo
hostile "over 64 KiB" big
hostile "path zone" gen "zone=../../etc/passwd\n"
hostile "unknown zone" gen "zone=Europe/Nowhere\n"
hostile "zone.tab zone without a file" gen "zone=Europe/Gone\n"
hostile "two zones" gen "zone=Europe/Zurich\nzone=Asia/Tokyo\n"
hostile "bad server" gen "ntp=a;b\n"
hostile "server with a space" gen "ntp=server x\n"
hostile "nine servers" nine
hostile "unknown key" gen "zone=Europe/Zurich\nfoo=bar\n"
hostile "not UTF-8" gen "zone=Europe/Z\xffrich\n"

# --- misuse
fresh
apply; rc=$?
check "no command: exit 2" test $rc -eq 2
apply status; rc=$?
check "unknown command: exit 2" test $rc -eq 2

if [[ $fail -eq 0 ]]; then echo "PASSED - thinfloe-time"; else echo "FAILED - thinfloe-time"; exit 1; fi
